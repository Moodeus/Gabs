<?php
/**
 * Printable product stock list (no layouts/main chrome), styled like
 * orders/invoice.php - a "Print" button triggers the browser's print
 * dialog, which can Save as PDF without needing a PDF library wired in.
 */
$company = document_company();
$byName  = (string) session()->get('name');
$lowCount = 0;
foreach ($products as $p) {
    if ((float) $p['Stock'] <= (float) $p['Low_Stock_Threshold']) {
        $lowCount++;
    }
}
?>
<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8" />
<title>Product Inventory · <?= esc($company['name']) ?></title>
<style>
<?= view('layouts/print_styles') ?>
</style>
</head>
<body>

<div class="no-print">
  <button type="button" onclick="window.print()"
    style="font:inherit;font-weight:bold;padding:8px 18px;border:0;background:#FFB606;cursor:pointer;">
    Print / Save as PDF
  </button>
</div>

<div class="sheet">

  <?= view('layouts/print_letterhead', [
      'company' => $company,
      'title' => 'PRODUCT INVENTORY',
      'badge' => 'AS OF ' . strtoupper(date('M j, Y', strtotime(database_today()))),
      'titleSize' => '17pt',
  ]) ?>

  <?= view('layouts/print_summary', [
      'heading' => 'Product stock list',
      'subheading' => 'Current stock, cost and selling price',
      'facts' => [
          ['Generated', date('F j, Y g:i A', strtotime(database_now()))],
          ['Generated by', $byName !== '' ? $byName : '—'],
          ['Low stock', (string) $lowCount],
      ],
  ]) ?>

  <table class="report-table">
    <thead>
      <tr>
        <th>#</th>
        <th>Product</th>
        <th class="num">Stock</th>
        <th class="num">Cost</th>
        <th class="num">Price</th>
        <th class="num">Low Stock Warning</th>
      </tr>
    </thead>
    <tbody>
      <?php foreach ($products as $i => $p): ?>
        <?php $low = (float) $p['Stock'] <= (float) $p['Low_Stock_Threshold']; ?>
        <tr>
          <td class="idx"><?= $i + 1 ?></td>
          <td class="strong"><?= esc($p['Name']) ?></td>
          <td class="num<?= $low ? ' low' : '' ?>"><?= esc(number_format((float) $p['Stock'], 2)) ?></td>
          <td class="num">&#8369; <?= esc(document_money($p['Cost'])) ?></td>
          <td class="num">&#8369; <?= esc(document_money($p['Price'])) ?></td>
          <td class="num"><?= esc(number_format((float) $p['Low_Stock_Threshold'], 2)) ?></td>
        </tr>
      <?php endforeach; ?>
      <?php if (empty($products)): ?>
        <tr><td class="empty" colspan="6">No products yet.</td></tr>
      <?php endif; ?>
    </tbody>
  </table>


  <?= view('layouts/print_footer', [
      'note' => 'Generated from the live system on ' . date('F j, Y g:i A', strtotime(database_now())) . '. Stock levels reflect that moment.',
      'reference' => 'Product Inventory',
  ]) ?>

</div>
</body>
</html>
